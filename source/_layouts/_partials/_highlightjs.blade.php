<script src="https://cdnjs.cloudflare.com/ajax/libs/highlight.js/11.11.2/highlight.min.js" defer></script>
<script>
    document.addEventListener('DOMContentLoaded', function() {
        if (!window.hljs) return;

        // Only blocks that declared a language. Auto-detection guesses badly on things
        // like psql output, and colours it as whatever language it looks closest to.
        hljs.configure({ cssSelector: 'pre code[class*="language-"]' });
        hljs.highlightAll();
    });
</script>
